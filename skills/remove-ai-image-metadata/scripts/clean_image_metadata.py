#!/usr/bin/env python3
"""Remove AI provenance metadata from common image containers without re-encoding."""

from __future__ import annotations

import argparse
from dataclasses import dataclass
import hashlib
import os
from pathlib import Path
import shutil
import struct
import sys
import tempfile
import zlib


PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"
JPEG_SIGNATURE = b"\xff\xd8"
GIF_SIGNATURES = (b"GIF87a", b"GIF89a")
SUPPORTED_EXTENSIONS = {".png", ".jpg", ".jpeg", ".webp", ".gif"}
AI_MARKERS = (
    b"openai",
    b"gpt image",
    b"chatgpt",
    b"dall-e",
    b"dall e",
    b"dalle",
    b"c2pa",
    b"content credentials",
    b"ai-generated",
    b"ai generated",
    b"generated by ai",
    b"generative ai",
    b"midjourney",
    b"stable diffusion",
    b"adobe firefly",
)


class ImageMetadataError(Exception):
    pass


@dataclass
class CleanResult:
    format_name: str
    dimensions: str
    removals: list[tuple[str, int, str]]
    cleaned: bytes
    encoded_hash: str


def marker_in(blob: bytes) -> bytes | None:
    normalized = blob.lower().replace(b"\x00", b"")
    for marker in AI_MARKERS:
        if marker in normalized:
            return marker
    return None


def sha256(parts) -> str:
    digest = hashlib.sha256()
    for part in parts:
        digest.update(part)
    return digest.hexdigest()


def detect_format(data: bytes, source: Path) -> str:
    if data.startswith(PNG_SIGNATURE):
        return "PNG"
    if data.startswith(JPEG_SIGNATURE):
        return "JPEG"
    if data.startswith(b"RIFF") and len(data) >= 12 and data[8:12] == b"WEBP":
        return "WebP"
    if data.startswith(GIF_SIGNATURES):
        return "GIF"
    raise ImageMetadataError(f"{source}: unsupported image container")


# PNG

PNG_TEXT_CHUNKS = {b"tEXt", b"zTXt", b"iTXt"}
PNG_ALL_METADATA = {b"caBX", b"tEXt", b"zTXt", b"iTXt", b"eXIf", b"tIME"}


def parse_png(data: bytes, source: Path) -> list[dict]:
    if not data.startswith(PNG_SIGNATURE):
        raise ImageMetadataError(f"{source}: invalid PNG signature")
    chunks = []
    pos = len(PNG_SIGNATURE)
    saw_iend = False
    while pos + 12 <= len(data):
        start = pos
        length = struct.unpack(">I", data[pos : pos + 4])[0]
        kind = data[pos + 4 : pos + 8]
        payload_start = pos + 8
        payload_end = payload_start + length
        end = payload_end + 4
        if end > len(data):
            raise ImageMetadataError(f"{source}: truncated PNG chunk")
        payload = data[payload_start:payload_end]
        stored_crc = struct.unpack(">I", data[payload_end:end])[0]
        crc = zlib.crc32(kind)
        crc = zlib.crc32(payload, crc) & 0xFFFFFFFF
        if crc != stored_crc:
            raise ImageMetadataError(f"{source}: invalid CRC in {kind!r}")
        chunks.append({"type": kind, "payload": payload, "raw": data[start:end]})
        pos = end
        if kind == b"IEND":
            saw_iend = True
            break
    if not saw_iend or pos != len(data) or not chunks or chunks[0]["type"] != b"IHDR":
        raise ImageMetadataError(f"{source}: malformed PNG structure")
    return chunks


def png_text(kind: bytes, payload: bytes) -> bytes:
    try:
        if kind == b"tEXt":
            return payload
        if kind == b"zTXt":
            keyword, rest = payload.split(b"\x00", 1)
            return keyword + b" " + zlib.decompress(rest[1:]) if rest[:1] == b"\x00" else payload
        if kind == b"iTXt":
            keyword, rest = payload.split(b"\x00", 1)
            compressed, method = rest[0], rest[1]
            language, rest = rest[2:].split(b"\x00", 1)
            translated, text = rest.split(b"\x00", 1)
            if compressed == 1 and method == 0:
                text = zlib.decompress(text)
            return b" ".join((keyword, language, translated, text))
    except (IndexError, ValueError, zlib.error):
        return payload
    return payload


def png_reason(chunk: dict, strip_all: bool) -> str | None:
    kind = chunk["type"]
    if kind == b"caBX":
        return "C2PA/Content Credentials caBX block"
    if strip_all and kind in PNG_ALL_METADATA:
        return "all-metadata mode"
    searchable = png_text(kind, chunk["payload"]) if kind in PNG_TEXT_CHUNKS else chunk["payload"]
    marker = marker_in(searchable)
    if marker is not None and bool(kind[0] & 0x20):
        return f"AI metadata marker: {marker.decode('ascii', errors='replace')}"
    return None


def clean_png(data: bytes, source: Path, strip_all: bool) -> CleanResult:
    chunks = parse_png(data, source)
    kept = []
    removals = []
    for chunk in chunks:
        reason = png_reason(chunk, strip_all)
        if reason:
            removals.append((chunk["type"].decode("latin-1"), len(chunk["payload"]), reason))
        else:
            kept.append(chunk)
    cleaned = PNG_SIGNATURE + b"".join(chunk["raw"] for chunk in kept)
    encoded_hash = sha256(chunk["payload"] for chunk in chunks if chunk["type"] == b"IDAT")
    width, height = struct.unpack(">II", chunks[0]["payload"][:8])
    return CleanResult("PNG", f"{width}x{height}", removals, cleaned, encoded_hash)


# JPEG

JPEG_STANDALONE = {0x01, 0xD8, 0xD9, *range(0xD0, 0xD8)}
JPEG_ALL_METADATA = {0xE1, 0xEB, 0xEC, 0xED, 0xFE}
JPEG_SOF = {0xC0, 0xC1, 0xC2, 0xC3, 0xC5, 0xC6, 0xC7, 0xC9, 0xCA, 0xCB, 0xCD, 0xCE, 0xCF}


def parse_jpeg(data: bytes, source: Path) -> list[dict]:
    if not data.startswith(JPEG_SIGNATURE):
        raise ImageMetadataError(f"{source}: invalid JPEG signature")
    segments = [{"marker": 0xD8, "payload": b"", "raw": data[:2]}]
    pos = 2
    while pos < len(data):
        start = pos
        if data[pos] != 0xFF:
            raise ImageMetadataError(f"{source}: expected JPEG marker at offset {pos}")
        while pos < len(data) and data[pos] == 0xFF:
            pos += 1
        if pos >= len(data):
            raise ImageMetadataError(f"{source}: truncated JPEG marker")
        marker = data[pos]
        pos += 1
        if marker == 0x00:
            raise ImageMetadataError(f"{source}: unexpected stuffed byte before scan data")
        if marker in JPEG_STANDALONE:
            segments.append({"marker": marker, "payload": b"", "raw": data[start:pos]})
            if marker == 0xD9:
                if pos != len(data):
                    raise ImageMetadataError(f"{source}: trailing data after JPEG EOI")
                return segments
            continue
        if pos + 2 > len(data):
            raise ImageMetadataError(f"{source}: truncated JPEG segment length")
        length = struct.unpack(">H", data[pos : pos + 2])[0]
        if length < 2 or pos + length > len(data):
            raise ImageMetadataError(f"{source}: invalid JPEG segment length")
        end = pos + length
        payload = data[pos + 2 : end]
        if marker == 0xDA:
            segments.append({"marker": marker, "payload": payload, "raw": data[start:]})
            return segments
        segments.append({"marker": marker, "payload": payload, "raw": data[start:end]})
        pos = end
    raise ImageMetadataError(f"{source}: JPEG ended before scan or EOI")


def jpeg_label(marker: int) -> str:
    if 0xE0 <= marker <= 0xEF:
        return f"APP{marker - 0xE0}"
    if marker == 0xFE:
        return "COM"
    return f"FF{marker:02X}"


def jpeg_reason(segment: dict, strip_all: bool) -> str | None:
    marker = segment["marker"]
    payload = segment["payload"]
    if strip_all and marker in JPEG_ALL_METADATA:
        return "all-metadata mode"
    if marker == 0xEB and (payload.startswith(b"JP") or marker_in(payload) is not None):
        return "C2PA/JUMBF APP11 provenance segment"
    if marker in {0xE1, 0xEC, 0xED, 0xFE}:
        found = marker_in(payload)
        if found is not None:
            extra = "; whole EXIF segment removed" if marker == 0xE1 and payload.startswith(b"Exif\x00\x00") else ""
            return f"AI metadata marker: {found.decode('ascii', errors='replace')}{extra}"
    return None


def jpeg_dimensions(segments: list[dict]) -> str:
    for segment in segments:
        if segment["marker"] in JPEG_SOF and len(segment["payload"]) >= 5:
            height, width = struct.unpack(">HH", segment["payload"][1:5])
            return f"{width}x{height}"
    return "unknown"


def jpeg_encoded_hash(segments: list[dict]) -> str:
    scan = next((segment["raw"] for segment in segments if segment["marker"] == 0xDA), b"")
    return sha256([scan])


def clean_jpeg(data: bytes, source: Path, strip_all: bool) -> CleanResult:
    segments = parse_jpeg(data, source)
    kept = []
    removals = []
    for segment in segments:
        reason = jpeg_reason(segment, strip_all)
        if reason:
            removals.append((jpeg_label(segment["marker"]), len(segment["payload"]), reason))
        else:
            kept.append(segment)
    cleaned = b"".join(segment["raw"] for segment in kept)
    return CleanResult("JPEG", jpeg_dimensions(segments), removals, cleaned, jpeg_encoded_hash(segments))


# WebP

WEBP_METADATA = {b"C2PA", b"EXIF", b"XMP "}
WEBP_FUNCTIONAL = {b"ICCP", b"ANIM", b"ANMF", b"ALPH", b"VP8 ", b"VP8L"}


def riff_chunk(kind: bytes, payload: bytes) -> bytes:
    padding = b"\x00" if len(payload) & 1 else b""
    return kind + struct.pack("<I", len(payload)) + payload + padding


def parse_webp(data: bytes, source: Path) -> list[dict]:
    if len(data) < 12 or data[:4] != b"RIFF" or data[8:12] != b"WEBP":
        raise ImageMetadataError(f"{source}: invalid WebP header")
    declared = struct.unpack("<I", data[4:8])[0] + 8
    if declared != len(data):
        raise ImageMetadataError(f"{source}: WebP RIFF size mismatch")
    chunks = []
    pos = 12
    while pos + 8 <= len(data):
        start = pos
        kind = data[pos : pos + 4]
        length = struct.unpack("<I", data[pos + 4 : pos + 8])[0]
        payload_start = pos + 8
        payload_end = payload_start + length
        end = payload_end + (length & 1)
        if end > len(data):
            raise ImageMetadataError(f"{source}: truncated WebP chunk")
        chunks.append({"type": kind, "payload": data[payload_start:payload_end], "raw": data[start:end]})
        pos = end
    if pos != len(data):
        raise ImageMetadataError(f"{source}: malformed WebP chunk layout")
    return chunks


def webp_reason(chunk: dict, strip_all: bool) -> str | None:
    kind = chunk["type"]
    if kind == b"C2PA":
        return "C2PA RIFF provenance chunk"
    if strip_all and kind in WEBP_METADATA:
        return "all-metadata mode"
    if kind in {b"EXIF", b"XMP "}:
        found = marker_in(chunk["payload"])
        if found is not None:
            return f"AI metadata marker: {found.decode('ascii', errors='replace')}"
    if kind not in WEBP_FUNCTIONAL and kind != b"VP8X":
        found = marker_in(chunk["payload"])
        if found is not None:
            return f"AI metadata marker in ancillary chunk: {found.decode('ascii', errors='replace')}"
    return None


def webp_dimensions(chunks: list[dict]) -> str:
    for chunk in chunks:
        if chunk["type"] == b"VP8X" and len(chunk["payload"]) >= 10:
            payload = chunk["payload"]
            width = 1 + int.from_bytes(payload[4:7], "little")
            height = 1 + int.from_bytes(payload[7:10], "little")
            return f"{width}x{height}"
        if chunk["type"] == b"VP8L" and len(chunk["payload"]) >= 5 and chunk["payload"][0] == 0x2F:
            payload = chunk["payload"]
            width = 1 + payload[1] + ((payload[2] & 0x3F) << 8)
            height = 1 + (payload[2] >> 6) + (payload[3] << 2) + ((payload[4] & 0x0F) << 10)
            return f"{width}x{height}"
        if chunk["type"] == b"VP8 " and len(chunk["payload"]) >= 10 and chunk["payload"][3:6] == b"\x9d\x01\x2a":
            width = int.from_bytes(chunk["payload"][6:8], "little") & 0x3FFF
            height = int.from_bytes(chunk["payload"][8:10], "little") & 0x3FFF
            return f"{width}x{height}"
    return "unknown"


def webp_encoded_hash(chunks: list[dict]) -> str:
    return sha256(chunk["payload"] for chunk in chunks if chunk["type"] in WEBP_FUNCTIONAL)


def clean_webp(data: bytes, source: Path, strip_all: bool) -> CleanResult:
    chunks = parse_webp(data, source)
    kept = []
    removals = []
    for chunk in chunks:
        reason = webp_reason(chunk, strip_all)
        if reason:
            removals.append((chunk["type"].decode("latin-1"), len(chunk["payload"]), reason))
        else:
            kept.append(dict(chunk))

    remaining_types = {chunk["type"] for chunk in kept}
    for chunk in kept:
        if chunk["type"] == b"VP8X" and len(chunk["payload"]) >= 10:
            payload = bytearray(chunk["payload"])
            if b"EXIF" not in remaining_types:
                payload[0] &= ~0x08
            if b"XMP " not in remaining_types:
                payload[0] &= ~0x04
            chunk["payload"] = bytes(payload)
            chunk["raw"] = riff_chunk(b"VP8X", chunk["payload"])

    body = b"WEBP" + b"".join(chunk["raw"] for chunk in kept)
    cleaned = b"RIFF" + struct.pack("<I", len(body)) + body
    return CleanResult("WebP", webp_dimensions(chunks), removals, cleaned, webp_encoded_hash(chunks))


# GIF

def read_gif_subblocks(data: bytes, pos: int, source: Path) -> tuple[int, bytes]:
    collected = bytearray()
    while True:
        if pos >= len(data):
            raise ImageMetadataError(f"{source}: truncated GIF sub-blocks")
        size = data[pos]
        pos += 1
        if size == 0:
            return pos, bytes(collected)
        if pos + size > len(data):
            raise ImageMetadataError(f"{source}: truncated GIF data block")
        collected.extend(data[pos : pos + size])
        pos += size


def parse_gif(data: bytes, source: Path) -> list[dict]:
    if not data.startswith(GIF_SIGNATURES) or len(data) < 13:
        raise ImageMetadataError(f"{source}: invalid GIF header")
    packed = data[10]
    gct_size = 3 * (2 ** ((packed & 0x07) + 1)) if packed & 0x80 else 0
    pos = 13 + gct_size
    if pos > len(data):
        raise ImageMetadataError(f"{source}: truncated GIF color table")
    blocks = [{"kind": "header", "label": None, "payload": b"", "raw": data[:pos]}]
    while pos < len(data):
        start = pos
        introducer = data[pos]
        if introducer == 0x3B:
            blocks.append({"kind": "trailer", "label": None, "payload": b"", "raw": data[pos : pos + 1]})
            pos += 1
            if pos != len(data):
                raise ImageMetadataError(f"{source}: trailing data after GIF trailer")
            return blocks
        if introducer == 0x21:
            if pos + 2 > len(data):
                raise ImageMetadataError(f"{source}: truncated GIF extension")
            label = data[pos + 1]
            end, payload = read_gif_subblocks(data, pos + 2, source)
            blocks.append({"kind": "extension", "label": label, "payload": payload, "raw": data[start:end]})
            pos = end
            continue
        if introducer == 0x2C:
            if pos + 10 > len(data):
                raise ImageMetadataError(f"{source}: truncated GIF image descriptor")
            local_packed = data[pos + 9]
            lct_size = 3 * (2 ** ((local_packed & 0x07) + 1)) if local_packed & 0x80 else 0
            pos += 10 + lct_size
            if pos >= len(data):
                raise ImageMetadataError(f"{source}: missing GIF LZW code size")
            pos += 1
            end, payload = read_gif_subblocks(data, pos, source)
            blocks.append({"kind": "image", "label": None, "payload": payload, "raw": data[start:end]})
            pos = end
            continue
        raise ImageMetadataError(f"{source}: unknown GIF block 0x{introducer:02X}")
    raise ImageMetadataError(f"{source}: GIF missing trailer")


def gif_reason(block: dict, strip_all: bool) -> str | None:
    if block["kind"] != "extension":
        return None
    label = block["label"]
    payload = block["payload"]
    is_c2pa = label == 0xFF and (payload.startswith(b"C2PA") or marker_in(payload) == b"c2pa")
    is_xmp = label == 0xFF and payload.startswith(b"XMP DataXMP")
    if is_c2pa:
        return "C2PA GIF application extension"
    if strip_all and (label in {0x01, 0xFE} or is_xmp):
        return "all-metadata mode"
    if label != 0xF9:
        found = marker_in(payload)
        if found is not None:
            return f"AI metadata marker: {found.decode('ascii', errors='replace')}"
    return None


def clean_gif(data: bytes, source: Path, strip_all: bool) -> CleanResult:
    blocks = parse_gif(data, source)
    kept = []
    removals = []
    for block in blocks:
        reason = gif_reason(block, strip_all)
        if reason:
            label = f"EXT-0x{block['label']:02X}"
            removals.append((label, len(block["raw"]), reason))
        else:
            kept.append(block)
    cleaned = b"".join(block["raw"] for block in kept)
    width, height = struct.unpack("<HH", data[6:10])
    encoded_hash = sha256(block["raw"] for block in blocks if block["kind"] == "image")
    return CleanResult("GIF", f"{width}x{height}", removals, cleaned, encoded_hash)


def clean_bytes(data: bytes, source: Path, strip_all: bool) -> CleanResult:
    format_name = detect_format(data, source)
    if format_name == "PNG":
        return clean_png(data, source, strip_all)
    if format_name == "JPEG":
        return clean_jpeg(data, source, strip_all)
    if format_name == "WebP":
        return clean_webp(data, source, strip_all)
    if format_name == "GIF":
        return clean_gif(data, source, strip_all)
    raise ImageMetadataError(f"{source}: unsupported image container")


def encoded_hash_for(data: bytes, source: Path) -> str:
    format_name = detect_format(data, source)
    if format_name == "PNG":
        return sha256(chunk["payload"] for chunk in parse_png(data, source) if chunk["type"] == b"IDAT")
    if format_name == "JPEG":
        return jpeg_encoded_hash(parse_jpeg(data, source))
    if format_name == "WebP":
        return webp_encoded_hash(parse_webp(data, source))
    if format_name == "GIF":
        return sha256(block["raw"] for block in parse_gif(data, source) if block["kind"] == "image")
    raise ImageMetadataError(f"{source}: unsupported image container")


def collect_images(inputs: list[Path], recursive: bool) -> list[Path]:
    found = []
    for item in inputs:
        item = item.expanduser()
        if not item.exists():
            raise FileNotFoundError(f"Path not found: {item}")
        if item.is_file():
            found.append(item.resolve())
            continue
        iterator = item.rglob("*") if recursive else item.iterdir()
        found.extend(path.resolve() for path in iterator if path.is_file() and path.suffix.lower() in SUPPORTED_EXTENSIONS)
    unique = sorted(set(found), key=lambda path: str(path).lower())
    if not unique:
        raise FileNotFoundError("No supported PNG, JPEG, WebP, or GIF files found")
    return unique


def write_atomic(destination: Path, data: bytes) -> None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    handle, temp_name = tempfile.mkstemp(
        prefix=destination.name + ".", suffix=".metadata-clean.tmp", dir=destination.parent
    )
    try:
        with os.fdopen(handle, "wb") as stream:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temp_name, destination)
    except Exception:
        try:
            os.unlink(temp_name)
        except FileNotFoundError:
            pass
        raise


def process_file(
    source: Path,
    destination: Path | None,
    strip_all: bool,
    backup_dir: Path | None,
    overwrite: bool,
) -> tuple[bool, int, str]:
    original = source.read_bytes()
    result = clean_bytes(original, source, strip_all)
    mode = "INSPECT" if destination is None else "CLEAN"
    print(f"[{mode}] {source} [{result.format_name} {result.dimensions}]")
    if result.removals:
        for label, length, reason in result.removals:
            print(f"  remove {label} ({length} bytes): {reason}")
    else:
        print("  no matching metadata found")
    if destination is None:
        return bool(result.removals), len(result.removals), result.format_name
    if destination != source and destination.exists() and not overwrite:
        raise FileExistsError(f"Output already exists; use --overwrite: {destination}")
    if destination == source and not result.removals:
        print("  unchanged: no rewrite needed")
        return False, 0, result.format_name
    if destination == source and backup_dir is not None:
        backup = backup_dir / source.name
        backup.parent.mkdir(parents=True, exist_ok=True)
        if backup.exists() and not overwrite:
            raise FileExistsError(f"Backup already exists; use --overwrite: {backup}")
        shutil.copy2(source, backup)
        print(f"  backup: {backup}")

    reparsed = clean_bytes(result.cleaned, destination or source, strip_all)
    if reparsed.removals:
        raise ImageMetadataError(f"{source}: matching metadata remains after cleaning")
    if encoded_hash_for(result.cleaned, destination or source) != result.encoded_hash:
        raise ImageMetadataError(f"{source}: encoded image payload changed before writing")
    write_atomic(destination, result.cleaned)
    written = destination.read_bytes()
    if encoded_hash_for(written, destination) != result.encoded_hash:
        raise ImageMetadataError(f"{source}: written encoded image payload changed")
    if clean_bytes(written, destination, strip_all).removals:
        raise ImageMetadataError(f"{source}: post-write metadata verification failed")
    print(f"  PASS: wrote {destination}; encoded image payload unchanged")
    return bool(result.removals), len(result.removals), result.format_name


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Remove AI provenance metadata from PNG, JPEG, WebP, and GIF without re-encoding."
    )
    parser.add_argument("inputs", nargs="+", type=Path, help="Image file(s) or folder(s)")
    parser.add_argument("--recursive", action="store_true", help="Include nested folders")
    write_group = parser.add_mutually_exclusive_group()
    write_group.add_argument("--in-place", action="store_true", help="Replace source files")
    write_group.add_argument("--output-dir", type=Path, help="Write clean copies here")
    parser.add_argument("--backup-dir", type=Path, help="Back up originals before --in-place cleaning")
    parser.add_argument(
        "--all-metadata",
        action="store_true",
        help="Also remove removable non-rendering metadata while preserving color and animation data",
    )
    parser.add_argument("--overwrite", action="store_true", help="Overwrite output/backups")
    return parser


def main() -> int:
    parser = build_parser()
    args = parser.parse_args()
    if args.backup_dir is not None and not args.in_place:
        parser.error("--backup-dir requires --in-place")
    output_dir = args.output_dir.resolve() if args.output_dir is not None else None
    backup_dir = args.backup_dir.resolve() if args.backup_dir is not None else None
    try:
        files = collect_images(args.inputs, args.recursive)
        print(f"Supported image files in scope: {len(files)}")
        seen_destinations = set()
        files_with_matches = 0
        action_items = 0
        formats = set()
        for source in files:
            destination = source if args.in_place else (output_dir / source.name if output_dir else None)
            if destination is not None:
                destination = destination.resolve()
                if destination in seen_destinations:
                    raise ValueError(f"Multiple inputs map to the same output: {destination}")
                seen_destinations.add(destination)
            matched, removed, format_name = process_file(
                source, destination, args.all_metadata, backup_dir, args.overwrite
            )
            files_with_matches += int(matched)
            action_items += removed
            formats.add(format_name)
        operation = "inspection" if not args.in_place and output_dir is None else "cleaning"
        item_label = "matching_items" if operation == "inspection" else "removed_items"
        print(
            f"SUMMARY: {operation} PASS; files={len(files)}; formats={','.join(sorted(formats))}; "
            f"files_with_matches={files_with_matches}; {item_label}={action_items}"
        )
        return 0
    except (FileNotFoundError, FileExistsError, OSError, ImageMetadataError, ValueError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


